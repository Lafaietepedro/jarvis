import unittest

from app.ui_frontend import read_ui_asset, read_ui_index


class UIFrontendTest(unittest.TestCase):
    def test_read_ui_index_contains_app_shell(self):
        html = read_ui_index()

        self.assertIn("<title>JARVIS</title>", html)
        self.assertIn('id="command-form"', html)
        self.assertIn('id="checkpoint-events"', html)
        self.assertIn('id="memory-audit-list"', html)
        self.assertIn('id="memory-audit-sample"', html)
        self.assertIn('id="memory-audit-form"', html)
        self.assertIn('id="memory-audit-intent"', html)
        self.assertIn('id="memory-audit-clear"', html)
        self.assertIn('id="memory-audit-delete-filtered"', html)
        self.assertIn('id="refresh-interval"', html)
        self.assertIn('/ui/assets/manifest.webmanifest', html)
        self.assertIn('/ui/assets/icon.svg', html)
        self.assertIn('/ui/assets/app.js', html)

    def test_read_ui_assets_are_whitelisted(self):
        script = read_ui_asset("app.js")
        styles = read_ui_asset("styles.css")
        manifest = read_ui_asset("manifest.webmanifest")
        icon = read_ui_asset("icon.svg")
        missing = read_ui_asset("../main.py")

        self.assertIsNotNone(script)
        self.assertIsNotNone(styles)
        self.assertIsNotNone(manifest)
        self.assertIsNotNone(icon)
        self.assertEqual(script[1], "text/javascript")
        self.assertEqual(styles[1], "text/css")
        self.assertEqual(manifest[1], "application/manifest+json")
        self.assertEqual(icon[1], "image/svg+xml")
        self.assertIn("renderCheckpointEvents", script[0])
        self.assertIn("checkpointMeta", script[0])
        self.assertIn("eventMeta", script[0])
        self.assertIn("checkpoint_detail", script[0])
        self.assertIn("event_detail", script[0])
        self.assertIn("source_label", script[0])
        self.assertIn("renderDiff", script[0])
        self.assertIn("renderEditPreview", script[0])
        self.assertIn("lineSpanLabel", script[0])
        self.assertIn("edit_preview", script[0])
        self.assertIn("checkpoint.diff", script[0])
        self.assertIn("normalizeAction", script[0])
        self.assertIn("requires_confirmation", script[0])
        self.assertIn("next_step", script[0])
        self.assertIn("blocked_count", script[0])
        self.assertIn("tracked_count", script[0])
        self.assertIn("proactive", script[0])
        self.assertIn("renderMemoryAudit", script[0])
        self.assertIn("memory_audit", script[0])
        self.assertIn("loadMemoryAudit", script[0])
        self.assertIn("/history/audit", script[0])
        self.assertIn("/history/delete", script[0])
        self.assertIn("deleteMemoryById", script[0])
        self.assertIn("deleteFilteredMemory", script[0])
        self.assertIn("window.confirm", script[0])
        self.assertIn("collectMemoryAuditFilters", script[0])
        self.assertIn("audit-grid", styles[0])
        self.assertIn("checkpoint-meta", styles[0])
        self.assertIn("checkpoint-diff", styles[0])
        self.assertIn("edit-preview", styles[0])
        self.assertIn("danger-button", styles[0])
        self.assertIn("jarvis.refreshInterval", script[0])
        self.assertIn('"start_url": "/ui"', manifest[0])
        self.assertIsNone(missing)


if __name__ == "__main__":
    unittest.main()
